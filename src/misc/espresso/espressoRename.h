/*
 *  espressoRename.h -- give the external symbols of Espresso a package prefix.
 *
 *  Espresso uses short global names (cube, debug, map, verify, ...) that
 *  collide with programs linking libabc.  Each Espresso source reaches this
 *  file through sparse.h after the system headers, so definitions and uses
 *  are renamed consistently.  Only Espresso_Main is called from outside.
 *
 *  When a global is added, regenerate the list from the names printed by
 *  "nm -g --defined-only" for the Espresso objects, excluding Espresso_*.
 */

